public class valueOf_type{
    public static void main(String[] args) {
        int s = 108;
        double m = 9.08;
        boolean g = true;
        System.out.println(String.valueOf(s)); // '108'
        System.out.println(String.valueOf(m)); // '9.08'
        System.out.println(String.valueOf(g)); // 'true'
    }
}